#!/usr/bin/env node
/*
 * Regenerates src/ui/brand/ScribeIcons/ScribeIcons.tsx and its registry from
 * the Figma SVG exports in src/ui/brand/ScribeIcons/svg/, listed in icons.json.
 *
 *   node scripts/gen-scribe-icons.mjs
 *
 * The SVGs are Figma's own `exportAsync({ format: "SVG_STRING" })` output and
 * are never edited by hand. This script only:
 *   - keeps each file's viewBox and native width/height (the default size),
 *   - turns the single paint of a `mono` icon into `currentColor`,
 *   - prefixes `id`s and their `url(#…)` references with the icon name, so two
 *     different icons inlined on one page cannot collide on Figma's `clip0_…`.
 * Re-export from Figma, drop the file in svg/, run this, commit both.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/ui/brand/ScribeIcons");
const list = JSON.parse(readFileSync(join(dir, "icons.json"), "utf8"));

// Not global: a /g regex keeps lastIndex between .test() calls.
const HAS_COLOUR = /#[0-9a-fA-F]{3,6}\b|\bblack\b|\bwhite\b/;

function convert({ name, file, mono }) {
  const svg = readFileSync(join(dir, "svg", file), "utf8").trim();
  const open = svg.match(/^<svg\b([^>]*)>/);
  if (!open) throw new Error(`${file}: no <svg> root`);
  const attr = (key) => open[1].match(new RegExp(`\\b${key}="([^"]*)"`))?.[1];
  const width = Number(attr("width"));
  const height = Number(attr("height"));
  const viewBox = attr("viewBox") ?? `0 0 ${width} ${height}`;
  if (!width || !height) throw new Error(`${file}: root width/height missing`);

  let body = svg.slice(open[0].length, svg.lastIndexOf("</svg>")).trim();

  const ids = [...body.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) {
    const scoped = `${name}-${id}`;
    body = body
      .replaceAll(`id="${id}"`, `id="${scoped}"`)
      .replaceAll(`url(#${id})`, `url(#${scoped})`)
      .replaceAll(`href="#${id}"`, `href="#${scoped}"`);
  }

  if (mono) {
    // <defs> only holds clip paths and masks here, whose fills never paint
    // (Figma's clip rects are always fill="white"), so they are left alone.
    const defsAt = body.indexOf("<defs>");
    const art = defsAt === -1 ? body : body.slice(0, defsAt);
    const defs = defsAt === -1 ? "" : body.slice(defsAt);
    const paints = new Set(
      [...art.matchAll(/\b(?:fill|stroke|stop-color)="([^"]+)"/g)]
        .map((m) => m[1].toLowerCase())
        .filter((v) => v !== "none" && !v.startsWith("url(")),
    );
    if (paints.size > 1) throw new Error(`${file}: marked mono but paints ${[...paints].join(", ")}`);
    body = art.replace(/\b(fill|stroke|stop-color)="(?!none|url\()([^"]+)"/g, '$1="currentColor"') + defs;
  } else if (!HAS_COLOUR.test(body)) {
    throw new Error(`${file}: marked multicolour but carries no colour`);
  }

  return { name, width, height, viewBox, body };
}

const icons = list.map(convert);

const header = `/*
 * GENERATED by scripts/gen-scribe-icons.mjs from ./svg/*.svg — do not edit.
 *
 * The TevScribe glyph set, exported from Figma (TevScribe-Product, page "Main
 * product") with exportAsync, unchanged apart from \`currentColor\` on the
 * single-colour glyphs and per-icon id prefixes. Each renders at its Figma size
 * by default; \`size\` sets the longer side and keeps the aspect ratio.
 *
 * Each constant is marked pure so a bundler drops the glyphs a consumer never
 * imports: primitives (Select's chevron, SearchField's lens) pull this module
 * in, and tsup inlines it into their entries.
 *
 * Markup is injected rather than transcribed to JSX for the same reason as
 * brand/Icons: it is machine artwork, re-exported wholesale. Every string is
 * a module constant; nothing interpolates caller input.
 */
import { cn } from "../../../utils.js";
import type { ScribeIconProps } from "./ScribeIcons.types.js";

function makeIcon(name: string, viewBox: string, width: number, height: number, markup: string) {
  function ScribeIcon({ size, className, strokeWidth, ...rest }: ScribeIconProps) {
    void strokeWidth;
    const scale = size ? size / Math.max(width, height) : 1;
    return (
      <svg
        {...rest}
        width={Math.round(width * scale * 100) / 100}
        height={Math.round(height * scale * 100) / 100}
        viewBox={viewBox}
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden={rest["aria-label"] ? undefined : true}
        data-slot="scribe-icon"
        data-icon={name}
        className={cn("shrink-0", className)}
        dangerouslySetInnerHTML={{ __html: markup }}
      />
    );
  }
  ScribeIcon.displayName = name;
  return ScribeIcon;
}
`;

const components = icons
  .map(
    (i) =>
      `\nexport const ${i.name} = /* @__PURE__ */ makeIcon(\n  "${i.name}",\n  "${i.viewBox}",\n  ${i.width},\n  ${i.height},\n  ${JSON.stringify(i.body)},\n);\n`,
  )
  .join("");

writeFileSync(join(dir, "ScribeIcons.tsx"), header + components);

const registry = `/* GENERATED by scripts/gen-scribe-icons.mjs — do not edit. */
import type { ScribeIcon } from "./ScribeIcons.types.js";
import {
${icons.map((i) => `  ${i.name},`).join("\n")}
} from "./ScribeIcons.js";

/**
 * Every TevScribe glyph by name, for config-driven call sites (a nav entry
 * that stores a name). Import the named component everywhere else.
 */
export const ScribeIcons: Record<string, ScribeIcon> = {
${icons.map((i) => `  ${i.name},`).join("\n")}
};
`;
writeFileSync(join(dir, "ScribeIcons.registry.ts"), registry);

console.log(`wrote ${icons.length} icons`);
